export function DashboardLanguageProvider({ role, children }) {
  const storageKey = `${role}-language`;
  const { user } = useAuthMe();
  const cachedLanguage = localStorage.getItem(storageKey) === "ar" ? "ar" : "en";
  const accountLanguage = ["en", "ar"].includes(user?.preferred_language)
    ? user.preferred_language
    : cachedLanguage;
  const [pendingLanguage, setPendingLanguage] = useState(null);
  const preferenceRequest = useRef(0);
  const language = pendingLanguage ?? accountLanguage;

  const changeLanguage = useCallback(async (nextLanguage) => {
    const safeLanguage = nextLanguage === "ar" ? "ar" : "en";
    const previousLanguage = language;
    const requestId = ++preferenceRequest.current;
    setPendingLanguage(safeLanguage);
    localStorage.setItem(storageKey, safeLanguage);

    try {
      await updateUserPreferences({ preferred_language: safeLanguage });
      if (requestId === preferenceRequest.current) setPendingLanguage(null);
    } catch (error) {
      if (requestId === preferenceRequest.current) {
        setPendingLanguage(null);
        localStorage.setItem(storageKey, previousLanguage);
      }
      console.error("Failed to update language preference:", error);
    }
  }, [language, storageKey]);

  const value = useMemo(
    () => ({
      language,
      direction: language === "ar" ? "rtl" : "ltr",
      changeLanguage,
      t: (text, variables = {}) => {
        const translated = language === "ar" ? arabic[text] || text : text;
        return Object.entries(variables).reduce(
          (result, [key, value]) => result.replaceAll(`{${key}}`, value),
          translated,
        );
      },
    }),
    [changeLanguage, language],
  );

  return (
    <DashboardLanguageContext.Provider value={value}>
      {children}
    </DashboardLanguageContext.Provider>
  );
}
